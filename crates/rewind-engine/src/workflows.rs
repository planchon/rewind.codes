/// A workflow version to register (`POST /v1/workflows`, the agent tool `save_workflow`).
#[derive(Debug, Clone)]
pub struct RegisterWorkflow {
    pub tenant: TenantId,
    pub name: String,
    pub description: Option<String>,
    pub script: Script,
    /// The toolset its runs call, already registered.
    pub toolset: Digest,
    pub schemas: WorkflowSchemas,
    /// The labels of the grant that saves it: part of the version, which only the principals
    /// that see them see. Empty for a tenant-wide save.
    pub labels: BTreeMap<String, String>,
    /// Generated by `rewind-codegen` from `schemas`: what the script is checked against besides
    /// its toolset.
    pub declarations: WorkflowDeclarations,
    /// Its parent, and how its suite differs from the parent's.
    pub suite: SuiteChanges,
}

#[derive(Debug, Clone, PartialEq, thiserror::Error)]
pub enum RegisterError {
    #[error(transparent)]
    Invalid(#[from] InvalidWorkflow),
    /// A schema cannot be compiled.
    #[error("the {which} schema cannot be used: {message}")]
    Schema { which: String, message: String },
    #[error("toolset {0} not found")]
    ToolsetNotFound(Digest),
    /// The script cannot run: it does not compile, imports what does not exist…
    #[error("the script is invalid: {0}")]
    InvalidScript(InvalidScript),
    /// The script does not type-check against its toolset and its own schemas.
    #[error("the script does not type-check: {}", first_error(.0))]
    TypeErrors(Vec<Diagnostic>),
    #[error(transparent)]
    Checker(#[from] CheckerError),
    #[error(transparent)]
    NulCharacter(#[from] NulCharacter),
    #[error(transparent)]
    Store(#[from] StoreError),
    #[error(transparent)]
    Blob(#[from] BlobError),
    /// The suite cannot be composed: a name, a reason or a test is wrong.
    #[error(transparent)]
    Suite(#[from] SuiteError),
    /// A stored test cannot be read.
    #[error("{0}")]
    CorruptTest(String),
    /// Tests of the suite did not pass: nothing was stored. Every report, in the suite's
    /// order.
    #[error("{} of {} tests did not pass", not_passed(.0), .0.len())]
    TestsFailed(Vec<TestReport>),
    /// The tests could not run, for a reason that is not theirs.
    #[error(transparent)]
    Tests(#[from] TestError),
}

/// Two versions with the same name, description, script, toolset, schemas and labels, whatever
/// their suites.
fn same_content(a: &Workflow, b: &Workflow) -> bool {
    a.labels() == b.labels()
        && a.name() == b.name()
        && a.description() == b.description()
        && a.script() == b.script()
        && a.toolset() == b.toolset()
        && a.schemas() == b.schemas()
}

fn not_passed(reports: &[TestReport]) -> usize {
    reports.iter().filter(|report| !report.passed).count()
}

impl From<SuiteLoadError> for RegisterError {
    fn from(error: SuiteLoadError) -> Self {
        match error {
            SuiteLoadError::Suite(error) => RegisterError::Suite(error),
            SuiteLoadError::Store(error) => RegisterError::Store(error),
            SuiteLoadError::Blob(error) => RegisterError::Blob(error),
            corrupt @ SuiteLoadError::Corrupt { .. } => {
                RegisterError::CorruptTest(corrupt.to_string())
            }
        }
    }
}

/// A run of a workflow version to start (`POST /v1/runs { workflow }`).
#[derive(Debug, Clone)]
pub struct StartWorkflow {
    pub tenant: TenantId,
    /// The end user the run acts for (`archi/06-storage-and-scale.md`, "Namespaces").
    pub namespace: NamespaceName,
    pub version: Digest,
    pub input: JsonValue,
    /// The run's TTL; [`EngineConfig::default_ttl`](crate::EngineConfig::default_ttl) when
    /// `None`.
    pub ttl: Option<Duration>,
    /// Its `workflow` is set from the version.
    pub metadata: RunMetadata,
    pub idempotency_key: Option<String>,
    pub credentials: Option<Credentials>,
}


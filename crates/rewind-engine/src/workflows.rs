    /// Checks a workflow and stores it as a new version: its name and signals, its schemas, its
    /// script against its toolset (the checks at start), then tsgo against the toolset's and its
    /// own declarations; then the gate: its suite, composed from its parent's, runs against it,
    /// and the version is stored only if every test passes
    /// (`archi/05-testing-and-observability.md`, "Suites and the gate"). Saving a version again
    /// under the same labels changes nothing; under other labels, it is another version,
    /// carrying them.
    pub async fn register_workflow<K: TypeChecker, L: MockLoader>(
        &self,
        request: RegisterWorkflow,
        checker: &K,
        kit: &TestKit<'_, L>,
    ) -> Result<StoredWorkflow, RegisterError> {
        text::refuse_nul("the script", request.script.source())?;
        text::refuse_nul("the workflow's name", &request.name)?;
        if let Some(description) = &request.description {
            text::refuse_nul("the workflow's description", description)?;
        }
        text::refuse_nul_in_labels(&request.labels)?;
        let workflow = Workflow::new(
            request.name,
            request.description,
            request.script.digest(),
            request.toolset,
            request.schemas,
        )?
        .with_labels(request.labels);
        let schemas = workflow.schemas();
        let named = [
            ("input".to_owned(), &schemas.input),
            ("output".to_owned(), &schemas.output),
        ];
        let signals = schemas
            .signals
            .iter()
            .map(|(name, schema)| (format!("{name:?} signal"), schema));
        for (which, schema) in named.into_iter().chain(signals) {
            if let Some(message) = Validator::compile(schema).unusable() {
                return Err(RegisterError::Schema {
                    which,
                    message: message.to_owned(),
                });
            }
        }
        let tenant = request.tenant;
        let stored = self
            .journal
            .get_toolset(&tenant, request.toolset)
            .await?
            .ok_or(RegisterError::ToolsetNotFound(request.toolset))?;
        let compiled = self
            .executor
            .compile(&request.script, &stored.toolset)
            .map_err(RegisterError::InvalidScript)?;
        let diagnostics = checker
            .check_workflow(&request.script, &stored.declarations, &request.declarations)
            .await?;
        if diagnostics
            .iter()
            .any(|diagnostic| diagnostic.severity == Severity::Error)
        {
            return Err(RegisterError::TypeErrors(diagnostics));
        }

        // The latest version saved under the same labels: the lineage of this scope. A version
        // saved under other labels, which a caller sees when its scope holds theirs, is another
        // lineage's.
        let latest = self
            .journal
            .workflow_versions(&tenant, workflow.name(), workflow.labels())
            .await?
            .into_iter()
            .find(|stored| &stored.labels == workflow.labels());
        // A save sent again, such as a retry whose answer was lost: the version it made.
        if let Some(latest) = &latest
            && self
                .saved_by(
                    &tenant,
                    &latest.workflow,
                    &workflow,
                    &request.suite,
                    kit.format,
                )
                .await?
        {
            return Ok(latest.clone());
        }

        // The gate.
        let parent = match request.suite.parent {
            Some(version) => {
                let parent = self
                    .journal
                    .get_workflow(&tenant, version)
                    .await?
                    .filter(|stored| stored.carries(workflow.labels()))
                    .ok_or(SuiteError::ParentNotFound(version))?;
                Some(parent.workflow)
            }
            None => latest.map(|stored| stored.workflow),
        };
        // The same workflow saved again on a parent named, its suite unchanged: that version.
        if let Some(parent) = &parent
            && same_content(parent, &workflow)
            && request.suite.tests.is_empty()
            && request.suite.update.is_empty()
            && request.suite.retire.is_empty()
            && let Some(stored) = self.journal.get_workflow(&tenant, parent.version()).await?
        {
            return Ok(stored);
        }
        let composed = self
            .compose_suite(&tenant, parent.as_ref(), &request.suite, kit.format)
            .await?;
        let reports = run_tests(
            &self.executor,
            kit.loader,
            &Subject {
                script: &request.script,
                toolset: &stored.toolset,
                interface: Some(workflow.schemas()),
            },
            &composed.tests,
            &kit.options,
        )
        .await?;
        if reports.iter().any(|report| !report.passed) {
            return Err(RegisterError::TestsFailed(reports));
        }
        let workflow = workflow.with_suite(composed.suite)?;
        self.store_tests(&tenant, &composed.tests, kit.format)
            .await?;

        self.journal
            .put_script(&tenant, &request.script, &compiled)
            .await?;
        let stored = self
            .journal
            .put_workflow(&tenant, &workflow, self.clock.now())
            .await?;
        tracing::debug!(workflow = %stored.workflow, "workflow registered");
        Ok(stored)
    }

    /// Whether `latest` is the version this save makes: the same content, and the suite the
    /// changes compose on `latest`'s own parent. So a save sent again (a retry whose answer was
    /// lost, a seed run twice) answers the version it made, instead of applying its changes a
    /// second time on top of it.
    async fn saved_by(
        &self,
        tenant: &TenantId,
        latest: &Workflow,
        workflow: &Workflow,
        changes: &SuiteChanges,
        format: TestFormat,
    ) -> Result<bool, RegisterError> {
        let base = latest.suite().parent;
        if !same_content(latest, workflow)
            || changes.parent.is_some_and(|named| Some(named) != base)
        {
            return Ok(false);
        }
        let base = match base {
            Some(version) => match self.journal.get_workflow(tenant, version).await? {
                Some(stored) => Some(stored.workflow),
                None => return Ok(false),
            },
            None => None,
        };
        // A change that does not apply to the parent is reported by the save itself.
        let Ok(composed) = self
            .compose_suite(tenant, base.as_ref(), changes, format)
            .await
        else {
            return Ok(false);
        };
        Ok(workflow
            .clone()
            .with_suite(composed.suite)
            .is_ok_and(|made| made.version() == latest.version()))
    }

    /// Starts a run of a workflow version: its input is checked against the version's schema,
    /// and the run is not type-checked again.
    pub async fn start_workflow(&self, request: StartWorkflow) -> Result<Created, StartError> {
        let stored = self
            .journal
            .get_workflow(&request.tenant, request.version)
            .await?
            .ok_or_else(|| StartError::WorkflowNotFound(request.version.to_hex()))?;
        let workflow = stored.workflow;
        if let Err(refused) =
            Validator::compile(&workflow.schemas().input).check("input", &request.input)
        {
            return Err(StartError::InvalidInput(refused_message(
                &format!("the input schema of {workflow}"),
                refused,
            )));
        }
        let bounds = self
            .namespace_bounds(&request.tenant, &request.namespace)
            .await?;
        let ttl = request.ttl.unwrap_or(bounds.default_ttl);
        if ttl.is_zero() || ttl > bounds.max_ttl {
            return Err(StartError::InvalidTtl {
                requested: ttl,
                max: bounds.max_ttl,
            });
        }
        self.check_workflow_lines(&request.tenant, &workflow, &bounds)
            .await?;
        let input = self.bounded_input(request.input)?;
        let mut metadata = request.metadata;
        metadata.workflow = Some(RunWorkflow {
            name: workflow.name().to_owned(),
            version: workflow.version(),
        });
        refuse_nul_in_metadata(&metadata, request.idempotency_key.as_deref())?;
        let epoch = *self.executor.epochs().last().ok_or(StartError::NoEpoch)?;
        self.create(NewRunRequest {
            tenant: request.tenant,
            namespace: request.namespace,
            script: workflow.script(),
            toolset: workflow.toolset(),
            input,
            epoch,
            mode: RunMode::Live,
            ttl,
            metadata,
            idempotency_key: request.idempotency_key,
            credentials: request.credentials,
        })
        .await
    }

    /// Refuses a workflow whose script has more lines than the namespace of its run takes.
    async fn check_workflow_lines(
        &self,
        tenant: &TenantId,
        workflow: &Workflow,
        bounds: &NamespaceBounds,
    ) -> Result<(), StartError> {
        if bounds.max_script_lines.is_none() {
            return Ok(());
        }
        let stored = self
            .journal
            .get_script(tenant, workflow.script())
            .await?
            .ok_or_else(|| {
                StartError::Store(StoreError::Backend(format!(
                    "the script of {workflow} is not stored"
                )))
            })?;
        bounds.check_lines(&stored.script)
    }

    /// Checks a signal sent to a run (by the API, a webhook, or a script): Rewind's own names
    /// are refused, and a run of a workflow only takes the signals its version declares, with
    /// a payload that matches their schema. `Ok(None)` for a run that is no workflow's.
    pub(crate) async fn check_signal(
        &self,
        record: &RunRecord,
        name: &str,
        payload: &JsonValue,
    ) -> Result<(), SignalRefused> {
        if is_reserved_signal(name) {
            return Err(SignalRefused::Reserved(name.to_owned()));
        }
        let Some(of) = &record.metadata.workflow else {
            return Ok(());
        };
        let stored = self
            .journal
            .get_workflow(&record.run.tenant, of.version)
            .await
            .map_err(SignalRefused::Store)?
            .ok_or_else(|| {
                SignalRefused::Store(StoreError::Backend(format!(
                    "the workflow version {} of run {} is not stored",
                    of.version, record.run.id
                )))
            })?;
        let workflow = &stored.workflow;
        let Some(schema) = workflow.schemas().signals.get(name) else {
            let declared: Vec<&str> = workflow
                .schemas()
                .signals
                .keys()
                .map(String::as_str)
                .collect();
            return Err(SignalRefused::Undeclared(format!(
                "run {} is a run of {workflow}, which does not declare the signal {name:?} \
                 (it declares {})",
                record.run.id,
                if declared.is_empty() {
                    "none".to_owned()
                } else {
                    declared
                        .iter()
                        .map(|name| format!("{name:?}"))
                        .collect::<Vec<_>>()
                        .join(", ")
                }
            )));
        };
        Validator::compile(schema)
            .check("payload", payload)
            .map_err(|refused| {
                SignalRefused::Payload(refused_message(
                    &format!("the {name:?} signal of {workflow}"),
                    refused,
                ))
            })
    }


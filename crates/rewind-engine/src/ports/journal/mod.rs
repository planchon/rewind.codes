//! What a run's history, inbox and tool tasks are made of, and what the catalog keeps of the
//! scripts, action sets and workflow versions they run (`archi/02-journal.md`,
//! `archi/03-execution.md`, "Activations", "Workflows across runs"; `archi/04-tools.md`,
//! "Tool task lifecycle"). The records the stores keep them in are their adapters':
//! [`PartitionStore`](crate::ports::PartitionStore) for a run, [`CatalogStore`](
//! crate::ports::CatalogStore) for the control plane.

mod activation;
mod runs;
mod tasks;
mod workflows;

use rewind_core::{ActionSet, RunId, Script, Timestamp};

pub use activation::{InboxItem, PayloadRecord, Trigger};
pub use runs::{
    Created, Enqueued, ForkParent, QUARANTINE_AFTER_FAILURES, Quarantine, QuarantineKind,
    RunMetadata, TraceContext,
};
pub use tasks::{
    ParkKind, ParkReason, TaskRef, TaskState, TaskToken, ToolTask, deferred_timeout_failure,
};
pub use workflows::{
    RunWorkflow, StartedBy, StoredWorkflow, TEST_GRACE, TestRecord, WorkflowFilter,
};

use super::checker::ToolDeclarations;
use super::executor::CompiledScript;
use super::tenancy::RunRef;

/// A script as stored: only scripts that compile are stored.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct StoredScript {
    pub script: Script,
    pub compiled: CompiledScript,
}

/// The title and description a person gave a script, for the organization, over the comment at
/// its top (`archi/04-tools.md`, "Script titles").
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ScriptTitle {
    pub title: String,
    pub description: Option<String>,
    /// Who set it: a principal, as the audit log names it.
    pub updated_by: String,
    pub updated_at: Timestamp,
}

/// A pinned action set as stored, with the declarations generated from it.
#[derive(Debug, Clone, PartialEq)]
pub struct StoredActionSet {
    pub action_set: ActionSet,
    pub declarations: ToolDeclarations,
}

/// The unguessable token of a webhook URL (`POST /hooks/{token}`), generated by the store from a
/// CSPRNG (at least 128 bits).
#[derive(Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct WebhookToken(pub String);

impl std::fmt::Debug for WebhookToken {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("WebhookToken(<redacted>)")
    }
}

/// What a webhook token is bound to: requests posted to it become `name` signals on the run.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct WebhookTarget {
    pub run: RunRef,
    pub name: String,
}

#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum StoreError {
    #[error("run {0} not found")]
    RunNotFound(RunId),
    /// A write that would break an invariant of the store, such as a history index that is
    /// already taken.
    #[error("conflict: {0}")]
    Conflict(String),
    #[error("storage backend error: {0}")]
    Backend(String),
}

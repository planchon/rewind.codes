/// A script as stored: only scripts that compile are stored.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct StoredScript {
    pub script: Script,
    pub compiled: CompiledScript,
}

/// A pinned toolset as stored, with the declarations generated from it.
#[derive(Debug, Clone, PartialEq)]
pub struct StoredToolset {
    pub toolset: Toolset,
    pub declarations: ToolDeclarations,
}

/// The unguessable token of a webhook URL (`POST /hooks/{token}`), generated by the store from a
/// CSPRNG (at least 128 bits).
#[derive(Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct WebhookToken(pub String);

impl std::fmt::Debug for WebhookToken {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("WebhookToken(<redacted>)")
    }
}

/// What a webhook token is bound to: requests posted to it become `name` signals on the run.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct WebhookTarget {
    pub run: RunRef,
    pub name: String,
}

#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum StoreError {
    /// The lease was lost: another worker acquired the run since.
    #[error("the lease on run {run_id} is lost (fence {fence} is stale)")]
    Fenced { run_id: RunId, fence: u64 },
    #[error("run {0} not found")]
    RunNotFound(RunId),
    /// The run's journal was archived: its history is in the archive, not in the store.
    #[error("the journal of run {0} is archived")]
    Archived(RunId),
    /// A write that would break an invariant of the store, such as a history index that is
    /// already taken.
    #[error("conflict: {0}")]
    Conflict(String),
    #[error("storage backend error: {0}")]
    Backend(String),
}

/// Scripts and toolsets; runs, histories, inboxes, timers and tool tasks; leases, fencing,
/// failure counts and quarantine; the feed; webhook tokens and subscriptions; tenants;
/// namespaces, their quotas, use and alerts; sticky affinity; payload metadata and references;
/// retention. API keys and tokens are the `AccessStore`'s.
///
/// The contract, checked by the conformance suite (feature `conformance`, module
/// `conformance::journal`):
///
/// - **Commit invariant.** `commit_activation` writes everything an activation produced in one
///   transaction, feed items included, and only if the lease's fence still matches.
/// - **Single writer.** `acquire_runnable`, `acquire_run` and `acquire_quarantined` increment
///   the fence and hand out at most one live lease per run.
/// - **Tenants.** Every key starts with the tenant: a run, a script, a toolset, a payload or a
///   task of one tenant is never visible to another. Run ids are unique across tenants.
/// - **Idempotency keys.** `create_run` with a key already used in the namespace returns the
///   existing run; `enqueue` with a key already seen for the run does nothing.
/// - **Quotas.** `create_run` checks the namespace's limits and the tenant's ceiling of
///   `active_runs`, `runs_per_month` and `scripts` under a lock of both, and counts what it
///   creates; crossing 80 % or 100 % of a counted quota, or a first refusal of `active_runs` in
///   a month, records one alert per tenant, namespace (or the tenant), quota, month and
///   threshold (`archi/06-storage-and-scale.md`, "Quotas").
/// - **Terminal runs.** A terminal commit clears the run's timers, tool tasks, inbox and
///   webhook tokens, and nothing is enqueued for a terminal run any more.
/// - **Watchers.** A run started by a script is watched by its starter (attached unless it is
///   detached), and by the forks that copied its start (`watch_run`). A terminal commit, in its
///   transaction, enqueues the run's end (`Activation::end`) as the signal
///   `rewind:ended:<run>` for each watcher that has not ended, under that name as idempotency
///   key, and `cancel_requested` for each run the ending run watches attached and that has not
///   ended.
/// - **Time.** Stores never read a clock: every method that depends on time takes `now`, and
///   every method that needs randomness for ordering takes it too. Tokens are the only values
///   a store draws from a CSPRNG.
pub trait JournalStore: Send + Sync {
    // ---------------------------------------------------------------------------------------
    // Scripts and toolsets

    /// Stores a script and its compiled form. Idempotent by digest: a second put changes
    /// nothing.
    fn put_script(
        &self,
        tenant: &TenantId,
        script: &Script,
        compiled: &CompiledScript,
    ) -> impl Future<Output = Result<(), StoreError>> + Send;

    fn get_script(
        &self,
        tenant: &TenantId,
        digest: Digest,
    ) -> impl Future<Output = Result<Option<StoredScript>, StoreError>> + Send;

    /// Stores a pinned toolset and its declarations. Idempotent by digest: a second put changes
    /// nothing.
    fn put_toolset(
        &self,
        tenant: &TenantId,
        toolset: &Toolset,
        declarations: &ToolDeclarations,
    ) -> impl Future<Output = Result<(), StoreError>> + Send;

    fn get_toolset(
        &self,
        tenant: &TenantId,
        digest: Digest,
    ) -> impl Future<Output = Result<Option<StoredToolset>, StoreError>> + Send;

    /// The tenant's toolsets, by digest.
    fn list_toolsets(
        &self,
        tenant: &TenantId,
    ) -> impl Future<Output = Result<Vec<StoredToolset>, StoreError>> + Send;

    // ---------------------------------------------------------------------------------------
    // Workflows

    /// Stores a workflow version, visible to the principals that see its labels, and returns it
    /// as stored, with a row of `workflow_tests` for each test of its suite, in one transaction.
    /// Idempotent by version: a second put changes nothing and returns the first. A new version
    /// that references a test without a row, or whose deletion has started, is refused
    /// (`Conflict`): it would point to a blob that may be gone.
    fn put_workflow(
        &self,
        tenant: &TenantId,
        workflow: &Workflow,
        now: Timestamp,
    ) -> impl Future<Output = Result<StoredWorkflow, StoreError>> + Send;

    fn get_workflow(
        &self,
        tenant: &TenantId,
        version: Digest,
    ) -> impl Future<Output = Result<Option<StoredWorkflow>, StoreError>> + Send;

    /// The versions of the workflow `name` that carry all of `labels`, newest first (the
    /// version created last first, ties in the order they were stored, last first). The first
    /// is the workflow's latest version.
    fn workflow_versions(
        &self,
        tenant: &TenantId,
        name: &str,
        labels: &BTreeMap<String, String>,
    ) -> impl Future<Output = Result<Vec<StoredWorkflow>, StoreError>> + Send;

    /// The versions of any workflow whose script is `script` and that carry all of `labels`,
    /// newest first (as `workflow_versions`).
    fn workflows_with_script(
        &self,
        tenant: &TenantId,
        script: Digest,
        labels: &BTreeMap<String, String>,
    ) -> impl Future<Output = Result<Vec<StoredWorkflow>, StoreError>> + Send;

    /// The latest version of each workflow of the tenant, among the versions that carry all of
    /// the filter's labels, sorted by name.
    fn latest_workflows(
        &self,
        filter: &WorkflowFilter,
    ) -> impl Future<Output = Result<Vec<StoredWorkflow>, StoreError>> + Send;

    // ---------------------------------------------------------------------------------------
    // The way in

    /// Creates a run and enqueues its `run_started`. With an idempotency key already used in
    /// the run's namespace, creates nothing and returns the existing run, whatever the quotas.
    /// Creates the namespace if it does not exist, with the tenant's defaults; a namespace being
    /// erased creates nothing (`NamespaceDeleting`).
    ///
    /// Under a lock of the namespace and of the tenant, refuses the run (`QuotaExceeded`) when,
    /// at the namespace's limit (its exception, else the tenant's default) then at the tenant's
    /// ceiling: the active (not terminal) runs reach `active_runs`; the runs created in the
    /// month of `created_at` reach `runs_per_month`; or the script is new to the namespace and
    /// its distinct scripts reach `scripts`. A first refusal of `active_runs` in a month records
    /// its alert. A created run counts in the day's `runs_started` of its namespace and of the
    /// tenant, adds one to its script's count in the namespace, sets the namespace's
    /// `last_active_at`, and records the alerts of `runs_per_month` and `scripts` whose 80 % or
    /// 100 % it crosses. A run id already used, in any tenant, is a `Conflict`.
    fn create_run(
        &self,
        run: NewRun,
        idempotency_key: Option<String>,
    ) -> impl Future<Output = Result<CreateRun, StoreError>> + Send;

    /// Enqueues a completion in the run's inbox. A key already seen for the run, or a terminal
    /// run, enqueues nothing. Keys are kept for the life of the run.
    fn enqueue(
        &self,
        run: &RunRef,
        completion: Completion,
        idempotency_key: Option<String>,
        now: Timestamp,
    ) -> impl Future<Output = Result<Enqueued, StoreError>> + Send;

    fn get_run(
        &self,
        run: &RunRef,
    ) -> impl Future<Output = Result<Option<RunRecord>, StoreError>> + Send;

    /// Makes `watcher`, which copied the call `seq` that started `run`, a watcher of `run`, never
    /// attached: a fork receives the end of the runs its copied history started
    /// (`archi/03-execution.md`, "Forks"). Says whether `run` has already ended: its end is then
    /// not enqueued for the watcher, and the caller enqueues it under the same key. `None` when
    /// `run` does not exist. Watching a run twice changes nothing.
    fn watch_run(
        &self,
        run: &RunRef,
        watcher: RunId,
        seq: Seq,
    ) -> impl Future<Output = Result<Option<Watched>, StoreError>> + Send;

    /// Runs of one tenant matching the filter, oldest first (`created_at`, then id).
    fn list_runs(
        &self,
        filter: &RunFilter,
    ) -> impl Future<Output = Result<Vec<RunRecord>, StoreError>> + Send;

    // ---------------------------------------------------------------------------------------
    // Leases and activations

    /// Leases a runnable run: one with something in its inbox, not leased (or whose lease
    /// expired), not quarantined, of an epoch in `epochs`, of a tenant in scope. The lease counts
    /// as an activation started: it increments the run's `attempts`, in the same transaction.
    ///
    /// - A run whose sticky worker is the caller is taken first, oldest inbox item first.
    /// - A run whose sticky worker is another worker is only offered once its oldest inbox item
    ///   has waited `sticky_grace`.
    /// - Otherwise the store draws a tenant among those with an eligible run (ordered by id,
    ///   index `draw` modulo their number), and takes that tenant's run whose oldest inbox item
    ///   is oldest.
    fn acquire_runnable(
        &self,
        request: &AcquireRunnable<'_>,
    ) -> impl Future<Output = Result<Option<Lease>, StoreError>> + Send;

    /// Leases a given run if it has not ended and is not leased, quarantined or not: to give
    /// up a quarantined run, to end a run by hand. It does not count in `attempts`.
    fn acquire_run(
        &self,
        run: &RunRef,
        owner: &str,
        now: Timestamp,
        lease_duration: Duration,
    ) -> impl Future<Output = Result<Option<Lease>, StoreError>> + Send;

    /// Leases a quarantined run of an epoch in `epochs` and of a tenant in scope that no worker
    /// of `build` has retried yet, and records that `build` retried it: a worker of a new build
    /// retries each quarantined run of its epochs and tenants once. A run of a tenant out of
    /// scope is neither leased nor marked: a worker of its own pool retries it. A retry that
    /// fails again calls `quarantine`. It does not count in `attempts`.
    fn acquire_quarantined(
        &self,
        owner: &str,
        build: &str,
        epochs: &[Epoch],
        tenants: &TenantScope,
        now: Timestamp,
        lease_duration: Duration,
    ) -> impl Future<Output = Result<Option<Lease>, StoreError>> + Send;

    /// Extends a lease whose fence still matches, and that was not given up, to
    /// `now + lease_duration`; `Fenced` otherwise. A worker calls it about every 10 s while it
    /// holds the run, replay included.
    fn renew(
        &self,
        lease: &Lease,
        now: Timestamp,
        lease_duration: Duration,
    ) -> impl Future<Output = Result<(), StoreError>> + Send;

    /// The history from index `from`. `Archived` once the run's journal is archived.
    fn load_history(
        &self,
        run: &RunRef,
        from: u64,
    ) -> impl Future<Output = Result<Vec<HistoryEntry>, StoreError>> + Send;

    /// The run's inbox, in arrival order. Items stay in the inbox until a commit consumes
    /// them.
    fn take_inbox(
        &self,
        lease: &Lease,
    ) -> impl Future<Output = Result<Vec<InboxItem>, StoreError>> + Send;

    /// Commits an activation atomically, if the lease's fence still matches. The entries must
    /// continue the history exactly (the next index first). In the same transaction: the
    /// payload rows and the run's payload references, the tool tasks (`approval` if their
    /// policy asks for it, else `ready` at `now`), timers, cancelled timers, one feed item per
    /// consumer when there are entries, the reset of the failure count and of the attempts, and
    /// the lease owner as the run's sticky worker. A terminal status clears the run's timers, tool tasks, inbox,
    /// webhook tokens and quarantine.
    ///
    /// A payload without its value (its value is in the `BlobStore`) needs a row that
    /// `reserve_payloads` created or kept, and whose deletion has not started: otherwise the
    /// commit is a `Conflict` and writes nothing, since its blob may be gone. A payload with its
    /// value creates its row or completes it, and stops its deletion.
    fn commit_activation(
        &self,
        lease: &Lease,
        activation: Activation,
        now: Timestamp,
    ) -> impl Future<Output = Result<(), StoreError>> + Send;

    /// Gives the lease up. Does nothing if the fence no longer matches.
    fn release(&self, lease: &Lease) -> impl Future<Output = Result<(), StoreError>> + Send;

    /// Drops the run's sticky priority if `owner` is still its sticky worker: the worker
    /// evicted the instance.
    fn forget_sticky(
        &self,
        run: &RunRef,
        owner: &str,
    ) -> impl Future<Output = Result<(), StoreError>> + Send;

    /// Counts an activation that failed and committed nothing, and keeps the lease until it
    /// expires. The [`QUARANTINE_AFTER_FAILURES`]-th failure in a row quarantines the run with
    /// `error` as its reason, and releases the lease.
    fn record_failure(
        &self,
        lease: &Lease,
        error: String,
        now: Timestamp,
    ) -> impl Future<Output = Result<Failures, StoreError>> + Send;

    /// Quarantines the run with `kind` and `reason`, and releases the lease without committing
    /// anything: `NonDeterminism` with the replay mismatch, or `Failures` when the run's last
    /// activations never finished.
    fn quarantine(
        &self,
        lease: &Lease,
        kind: QuarantineKind,
        reason: String,
        now: Timestamp,
    ) -> impl Future<Output = Result<(), StoreError>> + Send;

    /// Makes a quarantined run runnable again and resets its failure count and its attempts.
    /// Returns whether it was quarantined.
    fn release_quarantine(
        &self,
        run: &RunRef,
    ) -> impl Future<Output = Result<bool, StoreError>> + Send;

    // ---------------------------------------------------------------------------------------
    // Time: timers and deadlines, across tenants

    /// Enqueues `timer_fired` for up to `limit` timers due at `now`, earliest first, and
    /// deletes them. Returns how many fired.
    fn fire_due_timers(
        &self,
        now: Timestamp,
        limit: usize,
    ) -> impl Future<Output = Result<usize, StoreError>> + Send;

    /// The earliest `fire_at` of all timers.
    fn next_timer(&self) -> impl Future<Output = Result<Option<Timestamp>, StoreError>> + Send;

    /// Handles up to `limit` runs past their deadline at `now`, earliest deadline first: enqueues
    /// `cancel_requested { reason: "ttl" }`, once, for those that are neither terminal nor
    /// quarantined, and reports the quarantined ones, every time, until they are given up.
    fn expire_due_runs(
        &self,
        now: Timestamp,
        limit: usize,
    ) -> impl Future<Output = Result<ExpiredRuns, StoreError>> + Send;

    /// The earliest deadline of the runs that are neither terminal nor already expired.
    fn next_deadline(&self) -> impl Future<Output = Result<Option<Timestamp>, StoreError>> + Send;

    // ---------------------------------------------------------------------------------------
    // Tool tasks

    /// Claims up to `limit` tasks matching the filter: `ready` tasks whose `next_attempt_at`
    /// has passed, and `claimed` tasks whose claim expired, in the order they became due, then
    /// by run and seq. A task is only handed out while a concurrency slot is free: fewer than
    /// its policy's `concurrency` calls of the same tool in flight in its run, and for an MCP
    /// tool fewer than its server's concurrency in flight to that server (known by its tenant
    /// and name) under this `owner`.
    /// Calls in flight are claimed tasks whose claim has not expired, and deferred tasks.
    ///
    /// Each claim increments the attempt, issues a new token, and lasts the policy's heartbeat
    /// timeout.
    fn claim_tool_tasks(
        &self,
        owner: &str,
        filter: &TaskFilter,
        now: Timestamp,
        limit: usize,
    ) -> impl Future<Output = Result<Vec<ClaimedTask>, StoreError>> + Send;

    /// Extends the claim of `token` by its heartbeat timeout. Returns the claim's new end, the
    /// deadline of a deferred task (unchanged), or `None` if the token holds nothing any more.
    fn heartbeat_tool_task(
        &self,
        token: &TaskToken,
        now: Timestamp,
    ) -> impl Future<Output = Result<Option<Timestamp>, StoreError>> + Send;

    /// The earliest `next_attempt_at` later than `after` of the `ready` tasks, across tenants:
    /// when the next call retried after a backoff becomes due. In virtual time the driver jumps
    /// there, as to a timer, so that a retry never depends on what one engine remembers.
    fn next_tool_attempt(
        &self,
        after: Timestamp,
    ) -> impl Future<Output = Result<Option<Timestamp>, StoreError>> + Send;

    /// `claimed` → `ready` at `next_attempt_at`: a transient failure, retried with backoff.
    fn retry_tool_task(
        &self,
        token: &TaskToken,
        next_attempt_at: Timestamp,
    ) -> impl Future<Output = Result<TaskUpdate, StoreError>> + Send;

    /// `claimed` → `deferred` until `until`: the handler answers later with the same token.
    fn defer_tool_task(
        &self,
        token: &TaskToken,
        until: Timestamp,
    ) -> impl Future<Output = Result<TaskUpdate, StoreError>> + Send;

    /// `claimed` → `parked`.
    fn park_tool_task(
        &self,
        token: &TaskToken,
        reason: ParkReason,
    ) -> impl Future<Output = Result<TaskUpdate, StoreError>> + Send;

    /// `claimed` or `deferred` → done: deletes the task and enqueues its outcome in the run's
    /// inbox, atomically. The outcome of a task that no longer exists is dropped (`NotFound`).
    fn complete_tool_task(
        &self,
        token: &TaskToken,
        outcome: ToolOutcome,
        now: Timestamp,
    ) -> impl Future<Output = Result<TaskUpdate, StoreError>> + Send;

    /// `approval` or `parked` → `ready` at `now`: the harness lets the call go on. Approving a
    /// task parked by `SchemaChanged` sets its `schema_change_approved`.
    fn approve_tool_task(
        &self,
        task: &TaskRef,
        now: Timestamp,
    ) -> impl Future<Output = Result<TaskUpdate, StoreError>> + Send;

    /// `approval` or `parked` → done with `failure`: the script receives it as a `ToolError`.
    fn reject_tool_task(
        &self,
        task: &TaskRef,
        failure: ToolFailure,
        now: Timestamp,
    ) -> impl Future<Output = Result<TaskUpdate, StoreError>> + Send;

    /// Makes `ready` at `now` the tasks parked by `credentials_expired` in the scope, once the
    /// credentials were renewed. Returns how many.
    fn resume_parked(
        &self,
        scope: &ParkedScope,
        now: Timestamp,
    ) -> impl Future<Output = Result<usize, StoreError>> + Send;

    /// Ends up to `limit` deferred tasks whose deadline passed at `now`, with
    /// [`deferred_timeout_failure`]. Returns how many.
    fn expire_deferred_tool_tasks(
        &self,
        now: Timestamp,
        limit: usize,
    ) -> impl Future<Output = Result<usize, StoreError>> + Send;

    /// The tasks of a run, by seq: what the run's state shows as waiting.
    fn tool_tasks(
        &self,
        run: &RunRef,
    ) -> impl Future<Output = Result<Vec<ToolTask>, StoreError>> + Send;

    /// The task holding `token`: a claimed task, or a deferred one. `None` once the token holds
    /// nothing any more: the task is done, its run ended, it was claimed again, retried or
    /// parked. The API's calls on a claim carry only its token; the engine needs the task to
    /// apply its policy, its attempt and its run's deadline.
    fn tool_task(
        &self,
        token: &TaskToken,
    ) -> impl Future<Output = Result<Option<ToolTask>, StoreError>> + Send;

    // ---------------------------------------------------------------------------------------
    // Webhooks

    /// The token of the run's webhook for the signal `name`: created the first time, the same
    /// one afterwards.
    fn create_webhook_token(
        &self,
        run: &RunRef,
        name: &str,
    ) -> impl Future<Output = Result<WebhookToken, StoreError>> + Send;

    /// What a token is bound to; `None` for an unknown token, or one whose run has ended.
    fn resolve_webhook_token(
        &self,
        token: &WebhookToken,
    ) -> impl Future<Output = Result<Option<WebhookTarget>, StoreError>> + Send;

    /// Stores or replaces a subscription, by tenant and id.
    fn put_subscription(
        &self,
        subscription: &Subscription,
    ) -> impl Future<Output = Result<(), StoreError>> + Send;

    /// The tenant's subscriptions, by id.
    fn subscriptions(
        &self,
        tenant: &TenantId,
    ) -> impl Future<Output = Result<Vec<Subscription>, StoreError>> + Send;

    fn delete_subscription(
        &self,
        tenant: &TenantId,
        id: &str,
    ) -> impl Future<Output = Result<bool, StoreError>> + Send;

    // ---------------------------------------------------------------------------------------
    // Tests (`archi/05-testing-and-observability.md`, "Where tests are stored")

    /// Reserves the rows of tests before their blobs are written, in one transaction: a missing
    /// row is created as its record describes it; an existing row starts its [`TEST_GRACE`]
    /// again at `now`. Returns the tests whose deletion has started, left as they are: their
    /// blobs may be deleted at any time, so they cannot be referenced until their rows are gone.
    fn reserve_tests(
        &self,
        tenant: &TenantId,
        tests: &[TestRecord],
        now: Timestamp,
    ) -> impl Future<Output = Result<Vec<Digest>, StoreError>> + Send;

    /// A test's row; `None` for a test never stored, erased, or whose deletion has started.
    fn get_test(
        &self,
        tenant: &TenantId,
        digest: Digest,
    ) -> impl Future<Output = Result<Option<TestRecord>, StoreError>> + Send;

    /// Up to `limit` tests recorded from the runs of a namespace, for its erasure.
    fn namespace_tests(
        &self,
        tenant: &TenantId,
        namespace: &NamespaceName,
        limit: usize,
    ) -> impl Future<Output = Result<Vec<Digest>, StoreError>> + Send;

    /// Marks as being deleted, and returns, up to `limit` tests that no version references,
    /// stored or reserved at least [`TEST_GRACE`] before `now`, whose digest is not also a
    /// payload's, and whose deletion has not started, or started at least
    /// [`PAYLOAD_DELETION_TIMEOUT`] ago. Their blobs can be deleted, then their rows dropped.
    fn unreferenced_tests(
        &self,
        now: Timestamp,
        limit: usize,
    ) -> impl Future<Output = Result<Vec<(TenantId, Digest)>, StoreError>> + Send;

    /// Removes the rows of the given tests once their blobs are deleted: those still marked and
    /// that no version references; with `erased`, every given row, with the rows of
    /// `workflow_tests` that reference it (a namespace's erasure). Returns how many rows were
    /// removed.
    fn drop_tests(
        &self,
        tests: &[(TenantId, Digest)],
        erased: bool,
    ) -> impl Future<Output = Result<usize, StoreError>> + Send;

    // ---------------------------------------------------------------------------------------
    // Payloads

    /// A payload's row: size, preview, and the value when it is in the table tier.
    fn get_payload(
        &self,
        tenant: &TenantId,
        digest: Digest,
    ) -> impl Future<Output = Result<Option<PayloadRecord>, StoreError>> + Send;

    /// Reserves the rows of payloads whose values an activation writes to the `BlobStore`,
    /// before it writes them, in one transaction. A missing row is created as its record
    /// describes it, without references; a row without references starts its grace again at
    /// `now`. No cleanup deletes a reserved payload before its grace has passed again, so its
    /// blob is still there when the activation commits.
    ///
    /// Returns the payloads whose deletion has started (`forget_payloads`), left as they are:
    /// their blobs may be deleted at any time, so the activation commits their values in their
    /// rows instead.
    fn reserve_payloads(
        &self,
        tenant: &TenantId,
        payloads: &[PayloadRecord],
        now: Timestamp,
    ) -> impl Future<Output = Result<Vec<Digest>, StoreError>> + Send;

    /// Up to `limit` payloads that no run has referenced for longer than their tenant's
    /// `payload_grace`, at `now`, whose deletion has not started, or started at least
    /// [`PAYLOAD_DELETION_TIMEOUT`] ago, and whose digest is not also a test's: a blob is keyed
    /// by its digest, whatever holds it.
    fn unreferenced_payloads(
        &self,
        now: Timestamp,
        limit: usize,
    ) -> impl Future<Output = Result<Vec<(TenantId, Digest)>, StoreError>> + Send;

    /// Starts deleting the given payloads that `unreferenced_payloads` would still return at
    /// `now`, and returns those: their rows are marked as being deleted since `now`, and their
    /// blobs can be deleted. A payload referenced or reserved again since is kept. Once the
    /// blobs are deleted, `drop_payloads` removes the rows.
    fn forget_payloads(
        &self,
        payloads: &[(TenantId, Digest)],
        now: Timestamp,
    ) -> impl Future<Output = Result<Vec<(TenantId, Digest)>, StoreError>> + Send;

    /// Removes the rows of the given payloads whose deletion `forget_payloads` started at
    /// `started`, once their blobs are deleted. A row that a commit took back since, with its
    /// value, is kept, and so is a row whose deletion was started again. Returns how many rows
    /// were removed.
    fn drop_payloads(
        &self,
        payloads: &[(TenantId, Digest)],
        started: Timestamp,
    ) -> impl Future<Output = Result<usize, StoreError>> + Send;

    // ---------------------------------------------------------------------------------------
    // Retention

    /// Up to `limit` finished runs, not archived, that ended longer ago than their tenant's
    /// `retention.journal`, at `now`, and whose feed items are all applied: the read model, the
    /// traces and the webhooks still read the history of a run with items left.
    fn runs_to_archive(
        &self,
        now: Timestamp,
        limit: usize,
    ) -> impl Future<Output = Result<Vec<RunRef>, StoreError>> + Send;

    /// Removes the history of a finished run whose journal document is archived under
    /// `document`, and keeps its record and payload references. Returns `false` for a run that
    /// does not exist, has not ended, or still has feed items to apply.
    fn archive_run(
        &self,
        run: &RunRef,
        document: Digest,
        now: Timestamp,
    ) -> impl Future<Output = Result<bool, StoreError>> + Send;

    /// Up to `limit` archived runs whose archive is older than their tenant's
    /// `retention.archive`, at `now`.
    fn runs_to_delete(
        &self,
        now: Timestamp,
        limit: usize,
    ) -> impl Future<Output = Result<Vec<RunRef>, StoreError>> + Send;

    /// Erases a run at any time: its record, history, inbox, timers, tasks, keys, webhook
    /// tokens, feed items and payload references, and one from its script's count in its
    /// namespace (the count at zero is removed). A payload left without references starts its
    /// grace at `now`. Returns whether the run existed.
    fn delete_run(
        &self,
        run: &RunRef,
        now: Timestamp,
    ) -> impl Future<Output = Result<bool, StoreError>> + Send;

    // ---------------------------------------------------------------------------------------
    // Tenants

    /// Stores or replaces a tenant's settings.
    fn put_tenant(&self, tenant: &Tenant) -> impl Future<Output = Result<(), StoreError>> + Send;

    fn get_tenant(
        &self,
        id: &TenantId,
    ) -> impl Future<Output = Result<Option<Tenant>, StoreError>> + Send;

    /// The tenants with a record, by id.
    fn list_tenants(&self) -> impl Future<Output = Result<Vec<Tenant>, StoreError>> + Send;

    // ---------------------------------------------------------------------------------------
    // Namespaces, their use and their alerts

    /// Creates the namespace if it does not exist. With `exceptions`, replaces its exceptions;
    /// without, leaves them. A namespace being erased is left as it is (`Deleting`).
    fn put_namespace(
        &self,
        tenant: &TenantId,
        name: &NamespaceName,
        exceptions: Option<&Quotas>,
        now: Timestamp,
    ) -> impl Future<Output = Result<NamespaceWrite, StoreError>> + Send;

    fn get_namespace(
        &self,
        tenant: &TenantId,
        name: &NamespaceName,
    ) -> impl Future<Output = Result<Option<Namespace>, StoreError>> + Send;

    /// The tenant's namespaces matching the filter, each with its limits (its exceptions over
    /// the tenant's defaults) and its use of `filter.month`, without days. Ordered by the use of
    /// the order, the largest first, then by name; or by name. The page says how many match
    /// the filter across every page.
    fn list_namespaces(
        &self,
        filter: &NamespaceFilter,
    ) -> impl Future<Output = Result<NamespacePage, StoreError>> + Send;

    /// The use of a namespace, or of the tenant across its namespaces, in a month: CPU time and
    /// runs created over the month, with its days; active runs and distinct scripts now.
    fn namespace_usage(
        &self,
        tenant: &TenantId,
        of: &UsageOf,
        month: Month,
    ) -> impl Future<Output = Result<Usage, StoreError>> + Send;

    /// Whether the namespace has at least one run kept of this script: what a token may read.
    fn namespace_has_script(
        &self,
        tenant: &TenantId,
        name: &NamespaceName,
        script: Digest,
    ) -> impl Future<Output = Result<bool, StoreError>> + Send;

    /// Sets the namespace's `tokens_revoked_before` to `now`: its signed tokens issued earlier
    /// are refused. Returns whether the namespace exists.
    fn revoke_namespace_tokens(
        &self,
        tenant: &TenantId,
        name: &NamespaceName,
        now: Timestamp,
    ) -> impl Future<Output = Result<bool, StoreError>> + Send;

    /// Marks the namespace for erasure at `now`, if it is not yet: it takes no run any more.
    fn delete_namespace(
        &self,
        tenant: &TenantId,
        name: &NamespaceName,
        now: Timestamp,
    ) -> impl Future<Output = Result<DeleteNamespace, StoreError>> + Send;

    /// Up to `limit` namespaces marked for erasure, the oldest mark first.
    fn namespaces_to_erase(
        &self,
        limit: usize,
    ) -> impl Future<Output = Result<Vec<(TenantId, NamespaceName)>, StoreError>> + Send;

    /// Removes a namespace marked for erasure that has no run left, with its use and its
    /// alerts. The tenant's own rows of use and alerts stay.
    fn drop_namespace(
        &self,
        tenant: &TenantId,
        name: &NamespaceName,
    ) -> impl Future<Output = Result<DropNamespace, StoreError>> + Send;

    /// Adds CPU time to the day of each namespace (one that no longer exists is skipped) and of
    /// its tenant, sets the namespaces' `last_active_at`, and records the alerts of
    /// `cpu_per_month` whose 80 % or 100 % an addition crosses, at the namespace's limit and at
    /// the tenant's ceiling. Returns the alerts it recorded.
    fn record_usage(
        &self,
        deltas: &[UsageDelta],
        now: Timestamp,
    ) -> impl Future<Output = Result<Vec<QuotaAlert>, StoreError>> + Send;

    /// The alerts of a month: of one namespace, or every alert of the tenant (its own
    /// included); the newest first.
    fn quota_alerts(
        &self,
        tenant: &TenantId,
        namespace: Option<&NamespaceName>,
        month: Month,
    ) -> impl Future<Output = Result<Vec<QuotaAlert>, StoreError>> + Send;

    /// Claims up to `limit` alerts not yet sent and not claimed (or whose claim expired), the
    /// oldest first, until `now + lease_duration`, as `claim_feed` claims feed items.
    fn claim_quota_alerts(
        &self,
        owner: &str,
        now: Timestamp,
        lease_duration: Duration,
        limit: usize,
    ) -> impl Future<Output = Result<Vec<QuotaAlert>, StoreError>> + Send;

    /// Marks alerts sent at `now`. Unknown keys are ignored.
    fn ack_quota_alerts(
        &self,
        keys: &[QuotaAlertKey],
        now: Timestamp,
    ) -> impl Future<Output = Result<(), StoreError>> + Send;

    // ---------------------------------------------------------------------------------------
    // The feed

    /// Claims up to `limit` feed items of `consumer` that are not claimed or whose claim
    /// expired, oldest first, until `now + lease_duration`.
    fn claim_feed(
        &self,
        consumer: FeedConsumer,
        owner: &str,
        now: Timestamp,
        lease_duration: Duration,
        limit: usize,
    ) -> impl Future<Output = Result<Vec<FeedItem>, StoreError>> + Send;

    /// Deletes applied feed items. Unknown ids are ignored.
    fn ack_feed(&self, ids: &[u64]) -> impl Future<Output = Result<(), StoreError>> + Send;
}

//! Tool tasks (`archi/04-tools.md`, "Tool task lifecycle").
//!
//! ```text
//!               approve                claim                 answer, failure
//!   approval ───────────► ready ─────────────────► claimed ─────────────────────► done
//!      │ reject ▲  ▲  ▲     ▲   next_attempt_at,      │ │ │ the claim expires:       ▲
//!      ▼        │  │  │     │   a concurrency slot    │ │ │ claimed again,           │
//!    done       │  │  │     └──── retry (backoff) ────┘ │ │ attempt + 1              │
//!               │  │  └── approve, the secret ────┐   │ │                          │
//!               │  │      put again (resume_parked)│  │ └─► deferred ── complete, ─┤
//!               │  │                           parked ◄─┘   (a token)   fail,      │
//!               │  │                              │ reject              timeout    │
//!               │  │                              └────────────────────────────────┤
//! ```
//!
//! `done` is not a state the store keeps: a task that is done is deleted, and its outcome is in
//! the run's inbox. Attempts, backoff, leases, approvals and tokens live in the task, never in
//! the journal.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt;

use rewind_core::{
    Digest, Payload, Seq, Timestamp, ToolFailure, ToolFailureKind, ToolPolicy, ToolRoute,
};

use crate::ports::namespaces::NamespaceName;
use crate::ports::secrets::SecretId;
use crate::ports::tenancy::{RunRef, TenantId, TenantScope};

/// A tool task: the call `seq` of a run.
#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct TaskRef {
    pub run: RunRef,
    pub seq: Seq,
}

impl fmt::Display for TaskRef {
    /// `{run_id}/{seq}`, as the API names a task.
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}/{}", self.run.id, self.seq.0)
    }
}

/// An unguessable token for one claim of a task, generated by the store from a CSPRNG (at least
/// 128 bits). A claim's holder heartbeats, completes, fails, retries, defers or parks the task
/// with it. Once the task is claimed again, the previous token is no longer accepted; a
/// deferred task keeps its token until it is answered.
#[derive(Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct TaskToken(pub String);

impl fmt::Debug for TaskToken {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("TaskToken(<redacted>)")
    }
}

/// Where a task is in its lifecycle.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum TaskState {
    /// Waits for the harness's approval (the `approval` policy).
    Approval,
    /// Can be claimed once `next_attempt_at` has passed and a concurrency slot is free.
    Ready { next_attempt_at: Timestamp },
    /// Attempt n is in flight, under a claim kept alive by heartbeats. Once `until` has passed
    /// the task can be claimed again.
    Claimed { owner: String, until: Timestamp },
    /// The handler answers later, with the token of its claim, before `until`.
    Deferred { until: Timestamp },
    /// Waits for the harness after a schema change, a refused call or a missing secret.
    Parked(ParkReason),
}

impl TaskState {
    pub fn name(&self) -> &'static str {
        match self {
            TaskState::Approval => "approval",
            TaskState::Ready { .. } => "ready",
            TaskState::Claimed { .. } => "claimed",
            TaskState::Deferred { .. } => "deferred",
            TaskState::Parked(_) => "parked",
        }
    }
}

/// Why a task is parked.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ParkReason {
    pub kind: ParkKind,
    /// Written for the harness developer and the model: what changed, or what was refused.
    pub message: String,
}

/// Stored as `schema_changed`, `credentials_refused` and `secret_missing`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum ParkKind {
    /// The tool's current schema no longer matches the call (`tool.schema_changed`). Approved,
    /// the call is sent against the new schema: the task's `schema_change_approved` is set.
    SchemaChanged,
    /// The server answered 401 to the attached secret or to the signature
    /// (`credentials.expired`, reason `refused`). The secret put again, or the harness's
    /// approval, makes the task ready again.
    CredentialsRefused,
    /// The secret the run attached for the server no longer exists: parked by the engine before
    /// anything was sent (`credentials.expired`, reason `missing`). The secret put again makes
    /// the task ready again.
    SecretMissing,
}

impl ParkKind {
    pub fn as_str(self) -> &'static str {
        match self {
            ParkKind::SchemaChanged => "schema_changed",
            ParkKind::CredentialsRefused => "credentials_refused",
            ParkKind::SecretMissing => "secret_missing",
        }
    }

    /// Whether putting the secret the call reads again makes the task ready: a refusal or a
    /// missing secret (`archi/04-tools.md`, "Secrets").
    pub fn resumed_by_secret(self) -> bool {
        matches!(self, ParkKind::CredentialsRefused | ParkKind::SecretMissing)
    }
}

/// A task as the store keeps it.
#[derive(Debug, Clone, PartialEq)]
pub struct ToolTask {
    pub task: TaskRef,
    /// The toolset of the task's run.
    pub toolset: Digest,
    pub tool: String,
    pub route: ToolRoute,
    pub args: Payload,
    pub policy: ToolPolicy,
    pub state: TaskState,
    /// Claims so far: 0 before the first claim.
    pub attempt: u32,
    /// The harness approved the task while it was parked by
    /// [`SchemaChanged`](ParkKind::SchemaChanged): the call goes on against the tool's current
    /// schema, and the dispatcher no longer checks it. It stays set for the task's life.
    pub schema_change_approved: bool,
    pub created_at: Timestamp,
}

/// A task handed out by `claim_tool_tasks`.
#[derive(Debug, Clone, PartialEq)]
pub struct ClaimedTask {
    /// The task, in state `claimed`, its attempt incremented.
    pub task: ToolTask,
    pub token: TaskToken,
    /// The previous claim expired without an outcome: its holder died mid-call, and the call
    /// may or may not have taken effect. Under `at_most_once`, the engine fails the call with
    /// `outcome_unknown` instead of calling the tool again.
    pub previous_claim_expired: bool,
}

/// Which tasks a claim may hand out.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum TaskFilter {
    /// Every task, whatever its route and tenant: an engine in mock mode, where every call goes
    /// to the mocks.
    All,
    /// The tasks Rewind calls itself (MCP tools and built-ins), of the tenants in scope: the
    /// dispatcher's claim.
    Dispatched { tenants: TenantScope },
    /// The host tools of one tenant, optionally of one toolset and of some tools only: what a
    /// harness's worker long-polls through `GET /v1/tasks`.
    Host {
        tenant: TenantId,
        /// The tasks of this namespace's runs only: an end user's token.
        namespace: Option<NamespaceName>,
        /// The tasks of the runs carrying all of these labels only: a grant limited to labels.
        /// Empty: every run.
        labels: BTreeMap<String, String>,
        toolset: Option<Digest>,
        /// Empty: every host tool.
        tools: BTreeSet<String>,
    },
    /// The host tools, of the tenants in scope, whose claim expired and that cannot be handed
    /// out again: `at_most_once`, or `retry` with `max_attempts` claims made. The worker role
    /// claims them to fail them with `outcome_unknown` at once, so that a run does not wait for
    /// a harness's worker that may never poll again (`archi/04-tools.md`).
    Interrupted {
        tenants: TenantScope,
        max_attempts: u32,
    },
}

/// What an update of a task did.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum TaskUpdate {
    Applied,
    /// No such task, or not for this token: the task is done, its run ended, or it was claimed
    /// again since. An outcome reported for it is dropped.
    NotFound,
    /// The task is in a state the update does not apply to.
    InvalidState(TaskState),
}

/// The tasks `resume_parked` makes ready again.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ParkedScope {
    /// A secret was put again: the tasks parked by
    /// [`CredentialsRefused`](ParkKind::CredentialsRefused) or
    /// [`SecretMissing`](ParkKind::SecretMissing) whose run attaches it for the task's server or
    /// API: `org/<name>` for an organization's secret, in every namespace; `ns/<name>` for a
    /// namespace's, in the runs of that namespace only.
    Secret { tenant: TenantId, secret: SecretId },
}

/// What reads a secret (`archi/04-tools.md`, "Secrets": who reads what), as
/// `secret_usage` answers it before a deletion.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct SecretUsage {
    /// The active runs that attach it, oldest first, at most the `limit` given.
    pub active_runs: Vec<RunRef>,
    /// How many active runs attach it, all of them.
    pub active_total: u64,
    /// Those of the active runs with a call to a server or an API it serves that is parked or
    /// not yet sent, oldest first, at most the `limit` given.
    pub waiting_runs: Vec<RunRef>,
    /// How many of them, all of them.
    pub waiting_total: u64,
    /// The latest version of each workflow of the tenant that attaches it, by workflow name. A
    /// version attaching `ns/<name>` counts for the secret `<name>` of every namespace.
    pub versions: Vec<WorkflowAttaching>,
}

/// The latest version of a workflow, which attaches a secret.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct WorkflowAttaching {
    pub name: String,
    pub version: Digest,
    /// The servers and APIs it attaches the secret for, sorted.
    pub servers: Vec<String>,
}

/// The failure a deferred task ends with when no answer came before its deadline. Every store
/// writes this one, so that scripts see the same failure whatever the backend.
pub fn deferred_timeout_failure() -> ToolFailure {
    ToolFailure {
        kind: ToolFailureKind::Timeout,
        message: "the tool did not answer before its deadline".into(),
        data: None,
    }
}

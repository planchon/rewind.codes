//! `ptc-tools.d.ts`: the declarations of `ptc:tools` that tsgo checks scripts against.
//!
//! ```ts
//! declare module "ptc:tools" {
//!   /** Tools of the MCP server `github`. */
//!   export const github: {
//!     /** List the issues of a repository. */
//!     list_issues(args: { repo: string; state?: "open" | "closed" }): Promise<github.Issue[]>;
//!   };
//!   export namespace github {
//!     export interface Issue { … }
//!   }
//!
//!   /** Ask the end user a question. */
//!   export function ask_user(args: { question: string }): Promise<unknown>;
//! }
//! ```
//!
//! A namespace's types live in a namespace of the same name, merged with its value, so that two
//! servers can each have their `Issue`. The helper types of MCP content (`ToolContent`…) are
//! declared once, at the top, when a tool returns content.

use crate::model::{Export, ExportKind, Signature};
use crate::schema::Declaration;
use crate::ty::{Doc, Ty, block, jsdoc, property_name, render};

/// What an MCP tool without an output schema returns, and the types of its content blocks
/// (the MCP specification's `CallToolResult` content). The runtime adds `text()` and `json()`.
pub(crate) const CONTENT_TYPES: &str = r#"  /**
   * What an MCP tool without an output schema returns: the content it sent. `text()` and
   * `json()` read it.
   */
  export interface ToolContent<T = unknown> {
    /** The content blocks, in the order the tool sent them. */
    content: ContentBlock[];
    /** The structured result, when the tool sent one. */
    structuredContent?: T;
    /** The text blocks, joined by newlines. */
    text(): string;
    /**
     * `structuredContent` when the tool sent it, else `text()` parsed as JSON. Throws a
     * `SyntaxError` when the text is not JSON.
     */
    json<U = T>(): U;
  }

  /** One block of a tool's content. */
  export type ContentBlock =
    | TextContent
    | ImageContent
    | AudioContent
    | ResourceLink
    | EmbeddedResource;

  export interface TextContent {
    type: "text";
    text: string;
  }

  export interface ImageContent {
    type: "image";
    /** The image, in base64. */
    data: string;
    mimeType: string;
  }

  export interface AudioContent {
    type: "audio";
    /** The audio, in base64. */
    data: string;
    mimeType: string;
  }

  /** A link to a resource the tool did not include. */
  export interface ResourceLink {
    type: "resource_link";
    uri: string;
    name: string;
    title?: string;
    description?: string;
    mimeType?: string;
    size?: number;
  }

  /** A resource included in the content: its text, or its bytes in base64. */
  export interface EmbeddedResource {
    type: "resource";
    resource:
      | { uri: string; mimeType?: string; text: string }
      | { uri: string; mimeType?: string; blob: string };
  }
"#;

/// The whole module. `short` is the toolset's short digest, named in the header. With the
/// `http` tool, the first line is [`HTTP_TOOL_REFERENCE`](crate::HTTP_TOOL_REFERENCE).
pub(crate) fn module(short: &str, exports: &[Export<'_>], http_tool: bool) -> String {
    let mut out = String::new();
    if http_tool {
        out.push_str(crate::HTTP_TOOL_REFERENCE);
        out.push('\n');
    }
    out.push_str(&format!(
        "// `ptc:tools` of toolset {short}, generated by ptc-codegen: do not edit.\n\n\
         declare module \"ptc:tools\" {{\n"
    ));
    let content = exports.iter().any(|export| {
        export
            .tools
            .iter()
            .any(|signature| matches!(signature.result, Ty::Content(_)))
    });
    let mut first = true;
    if content {
        out.push_str(CONTENT_TYPES);
        first = false;
    }
    for export in exports {
        if !first {
            out.push('\n');
        }
        first = false;
        let tools: Vec<&Signature<'_>> = export.tools.iter().collect();
        let types: Vec<&Declaration> = export.scope.declarations.iter().collect();
        write_export(&mut out, export, &tools, &types);
    }
    out.push_str("}\n");
    out
}

/// One tool's declaration, with the types it uses: what `search_tools` returns.
pub(crate) fn tool(export: &Export<'_>, signature: &Signature<'_>) -> String {
    let used = export.types_used_by(signature);
    let types: Vec<&Declaration> = export
        .scope
        .declarations
        .iter()
        .filter(|declaration| used.contains(&declaration.name))
        .collect();
    let mut out = "declare module \"ptc:tools\" {\n".to_owned();
    write_export(&mut out, export, &[signature], &types);
    out.push_str("}\n");
    out
}

fn write_export(
    out: &mut String,
    export: &Export<'_>,
    tools: &[&Signature<'_>],
    types: &[&Declaration],
) {
    let qualifier = (!types.is_empty()).then_some(export.name);
    match export.kind {
        ExportKind::Namespace => {
            let owner = Doc {
                description: Some(export.owner()),
                tags: Vec::new(),
            };
            jsdoc(out, &owner, 1);
            out.push_str(&format!("  export const {}: {{\n", export.name));
            for signature in tools {
                jsdoc(out, &signature.doc, 2);
                out.push_str("    ");
                out.push_str(&property_name(signature.tool.local_name()));
                out.push_str(&parameters_and_result(signature, qualifier, 2));
                out.push_str(";\n");
            }
            out.push_str("  };\n");
        }
        ExportKind::Function => {
            for signature in tools {
                jsdoc(out, &signature.doc, 1);
                out.push_str(&format!("  export function {}", export.name));
                out.push_str(&parameters_and_result(signature, qualifier, 1));
                out.push_str(";\n");
            }
        }
    }
    if types.is_empty() {
        return;
    }
    out.push_str(&format!("  export namespace {} {{\n", export.name));
    for (index, declaration) in types.iter().enumerate() {
        if index > 0 {
            out.push('\n');
        }
        jsdoc(out, &declaration.doc, 2);
        match &declaration.ty {
            Ty::Object(object) => {
                out.push_str(&format!(
                    "    export interface {} {}\n",
                    declaration.name,
                    block(object, None, 2)
                ));
            }
            ty => {
                out.push_str(&format!(
                    "    export type {} = {};\n",
                    declaration.name,
                    render(ty, None, 2)
                ));
            }
        }
    }
    out.push_str("  }\n");
}

/// `(args: { … }): Promise<…>`.
fn parameters_and_result(
    signature: &Signature<'_>,
    qualifier: Option<&str>,
    indent: usize,
) -> String {
    let optional = if signature.args_optional { "?" } else { "" };
    format!(
        "(args{optional}: {}): Promise<{}>",
        render(&signature.args, qualifier, indent),
        render(&signature.result, qualifier, indent)
    )
}
